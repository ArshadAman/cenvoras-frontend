export const getGSTStateCode = (stateVal) => {
  if (!stateVal) return null;
  const s = String(stateVal).trim().toUpperCase();
  return STATE_TO_GST_CODE[s] || (s.length === 2 && /^\d+$/.test(s) ? s : null);
};

